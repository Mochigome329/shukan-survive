export function getCardArt(id: string): ArtRef {
  return Object.prototype.hasOwnProperty.call(CARD_ART, id) ? CARD_ART[id]! : battle;
}

export function getComboArt(id: string): ArtRef {
  return Object.prototype.hasOwnProperty.call(COMBO_ART, id) ? COMBO_ART[id]! : battle;
}
